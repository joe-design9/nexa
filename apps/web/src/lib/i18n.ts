export type Dict = typeof de;
export const dicts: Record<Locale, Dict> = { de, en };

/** Anzeigename einer Server-Kategorie (kanonischer API-Wert → UI-Text). */
export function categoryLabel(dict: Dict, name: string | undefined | null): string {
  if (!name) return '';
  return dict.categories[name] || name;
}

/** Bezeichnung einer Berechtigung. */
export function permLabel(dict: Dict, key: string): string {
  return dict.perms.labels[key] || key;
}

/**
 * Lokalisierte Meldung für einen API-Fehler: bekannter Fehlercode →
 * Wörterbuch-Text der aktiven Sprache; sonst die Server-Meldung.
 */
export function localizedApiError(code: string | undefined, serverMessage: string): string {
  if (code) {
    const translated = dicts[activeLocale].errors[code];
    if (translated) return translated;
  }
  return serverMessage;
}

/** Status-Text (ONLINE/IDLE/DND/INVISIBLE/OFFLINE) in der aktiven Sprache. */
export function statusText(dict: Dict, status?: string | null): string {
  switch (status) {
    case 'IDLE':
      return dict.status.idle;
    case 'DND':
      return dict.status.dnd;
    case 'INVISIBLE':
      return dict.status.invisible;
    case 'OFFLINE':
      return dict.status.offline;
    default:
      return dict.status.online;
  }
}

