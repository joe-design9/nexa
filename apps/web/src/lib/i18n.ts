// ─── Nexa i18n: zentrales Wörterbuch Deutsch/Englisch ────────────────────────
// Alle sichtbaren UI-Texte der Web-App stehen hier. Komponenten lesen über
// den Locale-Kontext (lib/locale.tsx → useLocale()) das aktive Wörterbuch;
// Nicht-Komponenten-Code (types.ts, api.ts, shared.ts) nutzt die aktive
// Sprache über getActiveLocale(). `en` ist als `typeof de` typisiert –
// fehlende oder zusätzliche Keys sind damit ein TypeScript-Fehler, und der
// Wörterbuch-Test (i18n.test.ts) prüft die Parität zusätzlich zur Laufzeit.

export type Locale = 'de' | 'en';

export const LOCALES: Locale[] = ['de', 'en'];
export const LOCALE_STORAGE_KEY = 'nexa_locale';
export const LOCALE_COOKIE = 'nexa_locale';
export const LOCALE_TAG: Record<Locale, string> = { de: 'de-DE', en: 'en-US' };

let activeLocale: Locale = 'de';
export function getActiveLocale(): Locale {
  return activeLocale;
}
export function setActiveLocale(l: Locale): void {
  activeLocale = l;
}
export function isLocale(v: unknown): v is Locale {
  return v === 'de' || v === 'en';
}

/** Erkennt die Sprache aus einem Accept-Language-/navigator.language-Wert. */
export function localeFromLanguageTag(tag: string | null | undefined): Locale {
  if (tag && tag.toLowerCase().startsWith('de')) return 'de';
  return 'en';
}

/** Platzhalter {name} in einer Vorlage ersetzen. */
export function fmt(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (vars[k] !== undefined ? String(vars[k]) : m));
}

// Datums-/Zeit-Helfer, die der aktiven Sprache folgen (für Nicht-Komponenten).
export function dateTag(): string {
  return LOCALE_TAG[activeLocale];
}
export function formatDateTime(iso: string): string {
  return new Date(iso).toLocaleString(dateTag());
}
export function formatDateOnly(iso: string): string {
  return new Date(iso).toLocaleDateString(dateTag());
}
export function formatDateLong(iso: string): string {
  return new Date(iso).toLocaleDateString(dateTag(), { day: '2-digit', month: 'long', year: 'numeric' });
}

